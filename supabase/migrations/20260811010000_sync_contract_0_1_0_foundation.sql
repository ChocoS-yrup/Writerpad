create or replace view public.sync_operation_states
with (security_invoker = true)
as
select
  operation.operation_id,
  operation.project_id,
  operation.batch_id,
  operation.entity_kind,
  operation.entity_id,
  operation.intent_kind,
  latest.event_sequence,
  latest.event_type,
  case latest.event_type
    when 'enqueued' then 'pending'
    when 'dispatch_started' then 'inflight'
    when 'retry_scheduled' then 'retry_wait'
    when 'blocked' then 'blocked'
    when 'conflict_detected' then 'conflict'
    when 'committed' then 'completed'
    when 'replayed' then 'completed'
    when 'cancel_requested' then 'cancelled'
    when 'superseded' then 'cancelled'
    else 'pending'
  end as state,
  latest.error_code,
  latest.recorded_at
from public.sync_operations operation
left join lateral (
  select event_sequence, event_type, error_code, recorded_at
  from public.sync_operation_events event
  where event.operation_id = operation.operation_id
  order by event_sequence desc
  limit 1
) latest on true;

